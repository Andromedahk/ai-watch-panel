package app.aiwatch.mobile

import java.util.Locale

private fun local(zh: String, en: String) = if (Locale.getDefault().language.startsWith("zh")) zh else en
fun requestTitle(key: String) = when (key) {
    "codex.input" -> local("Codex · 待回答", "Codex · Answer requested")
    "codex.commandApproval" -> local("Codex · 命令授权", "Codex · Command approval")
    "codex.fileApproval" -> local("Codex · 文件修改授权", "Codex · File change approval")
    else -> local("待处理请求", "Pending request")
}
fun requestLabel(key: String): String {
    val parts = key.split('.'); val number = parts.getOrNull(1)?.toIntOrNull()
    if (parts.size != 2 || number == null || number !in 1..32) return local("请在电脑查看", "Review on desktop")
    return when (parts[0]) { "question" -> local("第 $number 题", "Question $number"); "option" -> local("选项 $number", "Option $number"); else -> local("请在电脑查看", "Review on desktop") }
}
fun requestDetail(key: String): String {
    if (key == "input") return local("结构化问答", "Structured question")
    if (key == "fileChange") return local("文件修改", "File change")
    val executables = setOf("git", "python", "python3", "node", "bash", "sh", "zsh", "npm", "npx", "pnpm", "yarn", "cargo", "go", "swift", "make", "cmake")
    return if (key in executables) local("命令类别：", "Command category: ") + key else local("请在电脑查看操作详情", "Review the operation on the desktop")
}
fun requestNotice() = local("完整内容仅保留在电脑；手机仅显示类别和编号，请先在电脑确认上下文。", "Full content stays on the desktop. This phone shows only categories and numbers. Review the context on the desktop first.")

